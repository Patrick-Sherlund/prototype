const env = (name) => $env[name];

function requiredEnv(names) {
  const missing = names.filter((name) => !env(name));
  if (missing.length) throw new Error(`Missing environment variable(s): ${missing.join(', ')}`);
}

function docParagraphs(lines) {
  return {
    type: 'doc',
    version: 1,
    content: lines.map((line) => ({
      type: 'paragraph',
      content: line ? [{ type: 'text', text: String(line) }] : [],
    })),
  };
}

function chooseReviewTransition(transitions) {
  const candidates = transitions || [];
  const preferred = [/review/i, /ready for design/i, /ready for dev/i, /handoff/i, /done/i];
  return candidates.find((transition) => {
    const label = `${transition.name || ''} ${transition.to?.name || ''}`;
    return preferred.some((pattern) => pattern.test(label));
  });
}

async function jiraFetch(path, options = {}) {
  const baseUrl = env('JIRA_BASE_URL').replace(/\/$/, '');
  const response = await fetch(`${baseUrl}${path}`, {
    method: options.method || 'GET',
    headers: {
      Authorization: env('JIRA_AUTH_HEADER'),
      Accept: 'application/json',
      'Content-Type': 'application/json',
      ...(options.headers || {}),
    },
    body: options.body,
  });
  const text = await response.text();
  let data = {};
  if (text) {
    try {
      data = JSON.parse(text);
    } catch {
      data = { raw: text.slice(0, 600) };
    }
  }
  if (!response.ok) {
    const error = new Error(`Jira ${options.method || 'GET'} ${path} failed (${response.status}): ${text.slice(0, 700)}`);
    error.status = response.status;
    error.data = data;
    throw error;
  }
  return data;
}

function fileKeyFromDesignUrl(url) {
  const match = String(url || '').match(/figma\.com\/design\/([^/?#]+)/i);
  return match ? decodeURIComponent(match[1]) : '';
}

function persistDesign(input, status) {
  const staticData = $getWorkflowStaticData('global');
  staticData.figmaHandoffs = staticData.figmaHandoffs || {};
  staticData.figmaDesignMappings = staticData.figmaDesignMappings || {};

  const design = {
    figmaDesignFileKey: input.figmaDesignFileKey || input.design?.fileKey || fileKeyFromDesignUrl(input.figmaDesignUrl),
    figmaDesignUrl: input.figmaDesignUrl || input.design?.url || '',
    figmaDesignNodeId: input.figmaDesignNodeId || input.design?.nodeId || '',
  };

  if (input.jiraIssueKey && design.figmaDesignUrl) {
    staticData.figmaDesignMappings[input.jiraIssueKey] = {
      ...(staticData.figmaDesignMappings[input.jiraIssueKey] || {}),
      ...design,
      updatedAt: new Date().toISOString(),
    };
  }

  if (input.handoffId) {
    staticData.figmaHandoffs[input.handoffId] = {
      ...(staticData.figmaHandoffs[input.handoffId] || {}),
      status,
      jiraIssueKey: input.jiraIssueKey,
      jiraIssueUrl: input.jiraIssueUrl,
      design: {
        url: design.figmaDesignUrl,
        fileKey: design.figmaDesignFileKey,
        nodeId: design.figmaDesignNodeId,
      },
      slack: {
        channel: input.slackChannelId || env('SLACK_CHANNEL_ID') || '',
        threadTs: input.slackThreadTs || '',
      },
      updatedAt: new Date().toISOString(),
    };
  }

  return design;
}

function delay(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

async function updateJira(input) {
  const issueKey = input.jiraIssueKey;
  const versionLabel = input.figmaVersionLabel || `${input.figmaMakeFileKey || 'Figma Make'} ${input.figmaVersionId || ''}`.trim();
  const figmaUrl = input.figmaDesignUrl || input.design?.url;
  const makeSource = [
    input.figmaMakeUrl ? `Figma Make: ${input.figmaMakeUrl}` : '',
    input.figmaMakeFileKey ? `Figma Make file key: ${input.figmaMakeFileKey}` : '',
    input.figmaVersionId ? `Figma version ID: ${input.figmaVersionId}` : '',
  ].filter(Boolean);

  await jiraFetch(`/rest/api/3/issue/${encodeURIComponent(issueKey)}/comment`, {
    method: 'POST',
    body: JSON.stringify({
      body: docParagraphs([
        'Design handoff generated automatically from Figma Make.',
        '',
        'Source:',
        versionLabel,
        ...makeSource,
        '',
        'Editable Figma Design:',
        figmaUrl,
        '',
        'Generated by the automated Figma Make design-handoff workflow.',
        `Correlation ID: ${input.correlationId}`,
      ]),
    }),
  });

  let transitionApplied = '';
  try {
    const transitions = await jiraFetch(`/rest/api/3/issue/${encodeURIComponent(issueKey)}/transitions`);
    const reviewTransition = chooseReviewTransition(transitions.transitions);
    if (reviewTransition?.id) {
      await jiraFetch(`/rest/api/3/issue/${encodeURIComponent(issueKey)}/transitions`, {
        method: 'POST',
        body: JSON.stringify({ transition: { id: reviewTransition.id } }),
      });
      transitionApplied = reviewTransition.name || reviewTransition.to?.name || reviewTransition.id;
    }
  } catch (error) {
    console.log(
      JSON.stringify({
        stage: 'JIRA_TRANSITION_SKIPPED',
        correlationId: input.correlationId,
        jiraIssueKey: issueKey,
        error: String(error.message || error).slice(0, 500),
      }),
    );
  }

  return transitionApplied;
}

const input = $input.first().json;
if (input.requestFailed || !input.figmaReady || !input.claudeSuccess) return [{ json: input }];

try {
  requiredEnv(['JIRA_BASE_URL', 'JIRA_AUTH_HEADER']);
  const jiraIssueUrl = input.jiraIssueUrl || `${env('JIRA_BASE_URL').replace(/\/$/, '')}/browse/${input.jiraIssueKey}`;
  const design = persistDesign({ ...input, jiraIssueUrl }, 'figma_succeeded');
  let transitionApplied = '';
  let lastError;

  for (let attempt = 1; attempt <= 3; attempt += 1) {
    try {
      transitionApplied = await updateJira({ ...input, jiraIssueUrl, ...design });
      lastError = null;
      break;
    } catch (error) {
      lastError = error;
      console.log(
        JSON.stringify({
          stage: 'JIRA_COMPLETED_RETRY',
          correlationId: input.correlationId,
          jiraIssueKey: input.jiraIssueKey,
          attempt,
          error: String(error.message || error).slice(0, 500),
        }),
      );
      if (attempt < 3) await delay(attempt * 1000);
    }
  }

  if (lastError) throw lastError;

  persistDesign({ ...input, jiraIssueUrl, ...design }, 'completed');
  console.log(JSON.stringify({ stage: 'JIRA_COMPLETED', correlationId: input.correlationId, jiraIssueKey: input.jiraIssueKey }));

  return [
    {
      json: {
        ...input,
        ...design,
        jiraIssueUrl,
        jiraUpdated: true,
        jiraTransitionApplied: transitionApplied,
      },
    },
  ];
} catch (error) {
  const errorMessage = String(error.message || error).slice(0, 900);
  persistDesign(input, 'jira_failed');
  return [
    {
      json: {
        ...input,
        requestFailed: true,
        failureStage: 'JIRA_COMPLETED',
        errorMessage,
        jiraUpdated: false,
      },
    },
  ];
}
